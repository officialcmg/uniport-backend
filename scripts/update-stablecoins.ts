// Rewrites src/api/stablecoins.ts from 1Click's token list.
// Run: npm run update:stablecoins
//
// Only the large, fully backed dollar tokens are listed. A token that is not
// listed simply keeps the wider price buffer, so leaving one out is safe;
// listing one that can drift is not.
import { writeFileSync } from 'node:fs';

const SYMBOLS = new Set(['USDC', 'USDT', 'USDT0', 'DAI', 'xDAI']);

interface OneClickToken {
    assetId: string;
    symbol: string;
    blockchain: string;
    price?: number | string;
}

const response = await fetch('https://1click.chaindefuser.com/v0/tokens');
if (!response.ok) throw new Error(`1Click answered ${response.status}`);
const tokens = (await response.json()) as OneClickToken[];

const stable = tokens
    .filter((token) => SYMBOLS.has(token.symbol))
    // A listed symbol that is not trading at a dollar right now is left out.
    .filter((token) => Math.abs(Number(token.price) - 1) <= 0.01)
    .sort((a, b) => a.assetId.localeCompare(b.assetId));

if (stable.length < 10) throw new Error(`Only ${stable.length} stablecoins found; refusing to write the list.`);

const lines = stable.map((token) => `    '${token.assetId}', // ${token.symbol} on ${token.blockchain}`);
const file = `// Generated by scripts/update-stablecoins.ts from 1Click's token list. Do not edit by hand.
// Dollar tokens whose price barely moves against each other.

export const STABLECOIN_ASSETS: ReadonlySet<string> = new Set([
${lines.join('\n')}
]);
`;
writeFileSync(new URL('../src/api/stablecoins.ts', import.meta.url), file);
console.log(`Wrote ${stable.length} stablecoin assets.`);
